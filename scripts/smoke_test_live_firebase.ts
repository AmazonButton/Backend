import * as dotenv from 'dotenv';
dotenv.config();

import { cert, getApps, initializeApp } from 'firebase-admin/app';
import { getAuth } from 'firebase-admin/auth';
import * as fs from 'fs';
import * as path from 'path';
import * as readline from 'readline';

function promptTokenFromStdin(): Promise<string> {
  return new Promise((resolve) => {
    const rl = readline.createInterface({
      input: process.stdin,
      output: process.stdout,
    });
    rl.question('\n🔑 Nhập hoặc dán Firebase ID Token từ mobile (Enter để xác minh): ', (answer) => {
      rl.close();
      resolve(answer.trim());
    });
  });
}

async function runLiveFirebaseSmokeTest() {
  console.log('================================================================================');
  console.log('🔥 LIVE FIREBASE PHONE AUTHENTICATION SMOKE TEST');
  console.log('================================================================================\n');

  // 1. Verify Environment Variables
  const projectId = process.env.FIREBASE_PROJECT_ID;
  const clientEmail = process.env.FIREBASE_CLIENT_EMAIL;
  const privateKey = process.env.FIREBASE_PRIVATE_KEY?.replace(/\\n/g, '\n');
  const serviceAccountPath = process.env.FIREBASE_SERVICE_ACCOUNT_PATH;

  let authInstance: any = null;

  if (projectId && clientEmail && privateKey) {
    console.log(`[Config] Found environment credentials for Project ID: ${projectId}`);
    const app = getApps().length > 0 ? getApps()[0] : initializeApp({
      credential: cert({
        projectId,
        clientEmail,
        privateKey,
      }),
    });
    authInstance = getAuth(app);
  } else if (serviceAccountPath) {
    const resolvedPath = path.isAbsolute(serviceAccountPath)
      ? serviceAccountPath
      : path.resolve(process.cwd(), serviceAccountPath);

    if (fs.existsSync(resolvedPath)) {
      console.log(`[Config] Found service account file at: ${resolvedPath}`);
      const serviceAccount = JSON.parse(fs.readFileSync(resolvedPath, 'utf8'));
      const app = getApps().length > 0 ? getApps()[0] : initializeApp({
        credential: cert(serviceAccount),
      });
      authInstance = getAuth(app);
    }
  }

  if (!authInstance) {
    console.error('❌ [ERROR] Firebase Admin credentials not found!');
    console.error('   Please configure the following in your .env or environment:');
    console.error('   FIREBASE_PROJECT_ID=iot-button-e59d7');
    console.error('   FIREBASE_CLIENT_EMAIL=firebase-adminsdk-xxxxx@iot-button-e59d7.iam.gserviceaccount.com');
    console.error('   FIREBASE_PRIVATE_KEY="-----BEGIN PRIVATE KEY-----\\n...\\n-----END PRIVATE KEY-----\\n"');
    console.error('   (Or set FIREBASE_SERVICE_ACCOUNT_PATH to a valid JSON file outside source code)');
    process.exit(1);
  }

  // 2. Read Real Firebase ID Token strictly from Environment Variable or interactive Stdin
  // Security Invariant: Never accept ID Token via command line arguments (process.argv)
  // to prevent credential exposure in shell history (PSReadLine) and process table.
  let liveToken = process.env.LIVE_FIREBASE_ID_TOKEN?.trim();
  if (process.env.LIVE_FIREBASE_ID_TOKEN) {
    delete process.env.LIVE_FIREBASE_ID_TOKEN; // Scrub from memory immediately
  }

  if (!liveToken && process.stdin.isTTY) {
    liveToken = await promptTokenFromStdin();
  }

  if (!liveToken || !liveToken.trim()) {
    console.log('ℹ️  [AWAITING TOKEN] Firebase Admin SDK initialized successfully!');
    console.log('   Security Rule: Do NOT pass tokens on CLI arguments to avoid shell history leakage.');
    console.log('   To verify a real token from Android/iOS mobile client:');
    console.log('     Option A (Interactive stdin): Run `npx tsx scripts/smoke_test_live_firebase.ts` and paste token when prompted.');
    console.log('     Option B (Session env): Set `$env:LIVE_FIREBASE_ID_TOKEN="<token>"` in current terminal, then run script.\n');
    console.log('✔ Firebase Admin SDK connection and certificate configuration are VALID.');
    return;
  }

  console.log('\nVerifying Live Firebase ID Token with Google servers...');
  try {
    const decodedToken = await authInstance.verifyIdToken(liveToken.trim(), true);
    console.log('\n✅ [LIVE VERIFICATION SUCCESS]');
    console.log(`- Firebase UID     : ${decodedToken.uid}`);
    console.log(`- Phone Number     : ${decodedToken.phone_number || 'N/A'}`);
    console.log(`- Sign-in Provider : ${decodedToken.firebase?.sign_in_provider}`);
    console.log(`- Project (aud)    : ${decodedToken.aud}`);
    console.log(`- Issued At        : ${new Date(decodedToken.iat * 1000).toISOString()}`);
    console.log(`- Expires At       : ${new Date(decodedToken.exp * 1000).toISOString()}`);

    if (decodedToken.firebase?.sign_in_provider !== 'phone') {
      console.warn('⚠️  Warning: Token is valid but was NOT generated by phone authentication provider!');
    } else {
      console.log('✔ Token was confirmed from Firebase Phone Authentication.');
    }
  } catch (err: any) {
    console.error('\n❌ [LIVE VERIFICATION FAILED]:', err.message);
    process.exit(1);
  }
}

runLiveFirebaseSmokeTest();
